import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const contractUrl = new URL(
  '../../../docs/openapi/assistant-agent-v2.openapi.json',
  import.meta.url,
)
const outputUrl = new URL('../src/generated/agent-api.ts', import.meta.url)

function refName(value) {
  return value.slice(value.lastIndexOf('/') + 1)
}

function literal(value) {
  return JSON.stringify(value)
}

function typeExpression(schema, indent = '') {
  if (schema.$ref) return refName(schema.$ref)
  if (Object.hasOwn(schema, 'const')) return literal(schema.const)
  if (schema.enum) return schema.enum.map(literal).join(' | ')
  if (schema.anyOf) {
    return schema.anyOf.map((item) => typeExpression(item, indent)).join(' | ')
  }
  if (schema.oneOf) {
    return schema.oneOf.map((item) => typeExpression(item, indent)).join(' | ')
  }
  if (schema.type === 'array') {
    return `Array<${typeExpression(schema.items ?? {}, indent)}>`
  }
  if (schema.type === 'object') {
    if (schema.additionalProperties === true) return 'Record<string, unknown>'
    if (
      schema.additionalProperties &&
      typeof schema.additionalProperties === 'object'
    ) {
      return `Record<string, ${typeExpression(schema.additionalProperties, indent)}>`
    }
    if (!schema.properties) return 'Record<string, never>'
    const required = new Set(schema.required ?? [])
    const fields = Object.entries(schema.properties).map(([name, value]) => {
      const optional = required.has(name) ? '' : '?'
      return `${indent}  ${JSON.stringify(name)}${optional}: ${typeExpression(value, `${indent}  `)}`
    })
    return `{\n${fields.join('\n')}\n${indent}}`
  }
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'number' || schema.type === 'integer') return 'number'
  if (schema.type === 'null') return 'null'
  if (schema.type === 'string') return 'string'
  return 'unknown'
}

function declaration(name, schema) {
  if (schema.type !== 'object' || !schema.properties) {
    return `export type ${name} = ${typeExpression(schema)}\n`
  }
  const required = new Set(schema.required ?? [])
  const fields = Object.entries(schema.properties).map(([field, value]) => {
    const optional = required.has(field) ? '' : '?'
    return `  ${JSON.stringify(field)}${optional}: ${typeExpression(value, '  ')}`
  })
  return `export interface ${name} {\n${fields.join('\n')}\n}\n`
}

const document = JSON.parse(await readFile(contractUrl, 'utf8'))
const schemas = document.components?.schemas
if (!schemas || typeof schemas !== 'object') {
  throw new Error('OpenAPI contract does not contain components.schemas')
}

const body = Object.entries(schemas)
  .map(([name, schema]) => declaration(name, schema))
  .join('\n')
const generated = `// Generated by scripts/generate-agent-api-types.mjs. Do not edit.\n// Source: docs/openapi/assistant-agent-v2.openapi.json (${document.info.version})\n\n${body}`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = await readFile(outputUrl, 'utf8')
  } catch {
    // A missing file is reported as stale below.
  }
  if (current !== generated) {
    throw new Error('Generated Agent API types are stale; run npm run generate:agent-types')
  }
} else {
  await mkdir(fileURLToPath(new URL('../src/generated/', import.meta.url)), {
    recursive: true,
  })
  await writeFile(outputUrl, generated)
}
